#!/usr/bin/env node
/**
 * Generate Explorer schema artifacts from specifications TOML:
 *   - public/data/vocab.index.json
 *   - lib/opentide/generated/field-registry.ts
 *
 * Usage:
 *   node scripts/codegen-from-specs.mjs [--check] [specsDir]
 *
 * --check  Regenerate and exit non-zero if tracked outputs drift.
 */
import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  buildFieldRegistryFromPins,
  buildVocabIndexFromDir,
  resolveSpecsDir,
} from "./lib/spec-toml.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");

const VOCAB_OUT = path.join(ROOT, "public/data/vocab.index.json");
const FIELD_REGISTRY_OUT = path.join(
  ROOT,
  "lib/opentide/generated/field-registry.ts",
);

function defaultSpecsDir() {
  const candidates = [
    process.env.SPECIFICATIONS_REPO_ROOT,
    path.resolve(ROOT, "../specifications"),
    path.resolve(ROOT, "../../specifications"),
  ].filter(Boolean);

  for (const candidate of candidates) {
    const pins = path.join(candidate, "schemas/pins");
    if (fs.existsSync(pins)) return candidate;
  }

  return candidates[0] ?? path.resolve(ROOT, "../specifications");
}

function serializeFieldRegistry(registry) {
  const lines = [
    "/* eslint-disable */",
    "/* auto-generated by scripts/codegen-from-specs.mjs — do not edit */",
    "",
    'import type { ObjectType } from "@/lib/opentide/types";',
    "",
    "export type FieldFormat =",
    '  | "text"',
    '  | "pills"',
    '  | "markdown"',
    '  | "attack"',
    '  | "references"',
    '  | "number"',
    '  | "surface";',
    "",
    "export interface FieldDefinition {",
    "  path: string;",
    "  label: string;",
    "  format: FieldFormat;",
    "  vocab?: string;",
    "}",
    "",
  ];

  for (const [type, fields] of Object.entries(registry).sort(([a], [b]) =>
    a.localeCompare(b),
  )) {
    const constName = `${type.toUpperCase()}_FIELDS`;
    lines.push(
      `const ${constName}: FieldDefinition[] = ${JSON.stringify(fields, null, 2)};`,
      "",
    );
  }

  lines.push(
    "export const FIELD_REGISTRY: Record<ObjectType, FieldDefinition[]> = {",
    ...Object.keys(registry)
      .sort()
      .map((type) => `  ${type}: ${type.toUpperCase()}_FIELDS,`),
    "};",
    "",
  );

  return lines.join("\n");
}

export function codegenFromSpecs(specsDir) {
  const root = resolveSpecsDir(specsDir);
  const vocabDir = path.join(root, "vocabularies");
  const pinsDir = path.join(root, "schemas/pins");

  const vocabIndex = buildVocabIndexFromDir(vocabDir);
  const fieldRegistry = buildFieldRegistryFromPins(pinsDir);

  fs.mkdirSync(path.dirname(VOCAB_OUT), { recursive: true });
  fs.writeFileSync(VOCAB_OUT, `${JSON.stringify(vocabIndex, null, 2)}\n`);

  fs.mkdirSync(path.dirname(FIELD_REGISTRY_OUT), { recursive: true });
  fs.writeFileSync(
    FIELD_REGISTRY_OUT,
    `${serializeFieldRegistry(fieldRegistry)}\n`,
  );
  // Keep generated TS aligned with oxfmt so `fmt:check` after codegen stays green.
  execSync(`pnpm exec oxfmt ${JSON.stringify(FIELD_REGISTRY_OUT)}`, {
    cwd: ROOT,
    stdio: "pipe",
  });

  return {
    vocabCount: Object.keys(vocabIndex).length,
    fieldTypes: Object.keys(fieldRegistry).length,
    vocabOut: VOCAB_OUT,
    fieldRegistryOut: FIELD_REGISTRY_OUT,
  };
}

function gitDiff(paths) {
  const quoted = paths.map((p) => JSON.stringify(p)).join(" ");
  try {
    execSync(`git diff --exit-code -- ${quoted}`, {
      cwd: ROOT,
      stdio: ["ignore", "pipe", "pipe"],
    });
    return "";
  } catch (err) {
    if (err && typeof err === "object" && "status" in err && err.status === 1) {
      return String(err.stdout ?? "");
    }
    throw err;
  }
}

function main() {
  const args = process.argv.slice(2);
  const check = args.includes("--check");
  const specsDir = args.find((a) => !a.startsWith("-")) ?? defaultSpecsDir();

  const result = codegenFromSpecs(specsDir);
  console.log(
    `Codegen from ${specsDir}: ${result.vocabCount} vocabs → ${path.relative(ROOT, result.vocabOut)}`,
  );
  console.log(
    `  ${result.fieldTypes} object types → ${path.relative(ROOT, result.fieldRegistryOut)}`,
  );

  if (check) {
    const diff = gitDiff([result.vocabOut, result.fieldRegistryOut]);
    if (diff.trim()) {
      console.error(
        "\nGenerated schema artifacts are out of date. Run:\n  pnpm codegen:specs\n",
      );
      console.error(diff);
      process.exit(1);
    }
    console.log("Schema artifacts are up to date.");
  }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  try {
    main();
  } catch (err) {
    console.error(err instanceof Error ? err.message : err);
    process.exit(1);
  }
}
